from dataclasses import dataclass

from src.models.macd import MACD


@dataclass(slots=True)
class MACDResult:
    """
    Represents the output of the MACD indicator.

    value
        Latest MACD observation.

    series
        Historical MACD observations.

    trading_signal
        Trading signal generated by MACD.

    trend
        Human-readable explanation.
    """

    name: str

    value: MACD | None

    series: list[MACD]

    trading_signal: str | None = None
    
    trend: str | None = None